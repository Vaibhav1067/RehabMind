"""Prepare a hosted Postgres (e.g. Neon) for RehabMind: roles, database, privileges.

Does what docker/postgres/initdb does for the in-stack database, with the same role split:
  rehabmind_migrator - owns the database and schema; used only by Alembic.
  rehabmind_app      - runtime role; DML only.

Usage (from backend/):  uv run python -m app.scripts.setup_external_db
The admin connection string is read without echo, never from an argument. The generated
role passwords are written to .env.space (git-ignored) at the repository root: copy them
into the host's secret settings. Safe to re-run: it rotates both passwords.
"""

import asyncio
import getpass
import os
import secrets
import sys
from pathlib import Path
from urllib.parse import unquote, urlparse

import asyncpg

DB = "rehabmind"
OUT = Path(__file__).resolve().parents[3] / ".env.space"


async def _role(conn: asyncpg.Connection, name: str, password: str) -> None:
    # token_urlsafe output contains no quote characters; DDL cannot take bind parameters.
    exists = await conn.fetchval("SELECT 1 FROM pg_roles WHERE rolname = $1", name)
    verb = "ALTER" if exists else "CREATE"
    await conn.execute(f"{verb} ROLE {name} LOGIN PASSWORD '{password}'")


async def main() -> None:
    dsn = os.environ.get("REHABMIND_ADMIN_DSN") or getpass.getpass(
        "Admin connection string (postgresql://...): "
    )
    u = urlparse(dsn.strip().strip("'\""))
    if u.scheme not in ("postgresql", "postgres") or not u.hostname or not u.username:
        sys.exit("not a postgresql:// connection string")
    # Use the direct endpoint: session features break behind Neon's transaction pooler.
    host = u.hostname.replace("-pooler.", ".")
    admin = {
        "host": host,
        "port": u.port or 5432,
        "user": unquote(u.username),
        "password": unquote(u.password or ""),
        "ssl": "require",
    }
    migrator_pw, app_pw = secrets.token_urlsafe(32), secrets.token_urlsafe(32)

    conn = await asyncpg.connect(**admin, database=u.path.lstrip("/") or "postgres")
    try:
        await _role(conn, "rehabmind_migrator", migrator_pw)
        await _role(conn, "rehabmind_app", app_pw)
        await conn.execute("GRANT rehabmind_migrator TO CURRENT_USER")
        if not await conn.fetchval("SELECT 1 FROM pg_database WHERE datname = $1", DB):
            await conn.execute(f"CREATE DATABASE {DB} OWNER rehabmind_migrator")
            print(f"created database {DB}")
    finally:
        await conn.close()

    # The rest runs as the database owner, inside the new database.
    conn = await asyncpg.connect(
        host=host,
        port=admin["port"],
        user="rehabmind_migrator",
        password=migrator_pw,
        database=DB,
        ssl="require",
    )
    try:
        await conn.execute(
            f"""
            REVOKE ALL ON DATABASE {DB} FROM PUBLIC;
            GRANT CONNECT, TEMPORARY ON DATABASE {DB} TO rehabmind_app;
            ALTER SCHEMA public OWNER TO rehabmind_migrator;
            REVOKE ALL ON SCHEMA public FROM PUBLIC;
            GRANT USAGE ON SCHEMA public TO rehabmind_app;
            ALTER DEFAULT PRIVILEGES FOR ROLE rehabmind_migrator IN SCHEMA public
              GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO rehabmind_app;
            ALTER DEFAULT PRIVILEGES FOR ROLE rehabmind_migrator IN SCHEMA public
              GRANT USAGE, SELECT ON SEQUENCES TO rehabmind_app;
            """
        )
    finally:
        await conn.close()

    OUT.write_text(
        "# Generated by app.scripts.setup_external_db. Never commit.\n"
        f"POSTGRES_HOST={host}\n"
        f"POSTGRES_MIGRATOR_PASSWORD={migrator_pw}\n"
        f"POSTGRES_APP_PASSWORD={app_pw}\n",
        encoding="utf-8",
    )
    print(f"database ready; wrote {OUT.name}")


if __name__ == "__main__":
    asyncio.run(main())
